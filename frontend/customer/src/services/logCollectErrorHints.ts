/** 按错误码取建议；未知码返回 null，由界面指向任务详情。 */
export function logCollectErrorHint(code?: string | null): LogCollectErrorHint | null {
  const key = String(code || '').trim().toUpperCase()
  if (!key) return null
  return HINTS[key] || null
}
